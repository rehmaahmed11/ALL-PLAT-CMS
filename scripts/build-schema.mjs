#!/usr/bin/env node
// Turns src/db/schema.sql into src/db/schema.generated.ts so the Worker can run
// migrations without needing a .sql text-module rule in wrangler.toml.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sql = readFileSync(join(root, 'src/db/schema.sql'), 'utf8');

// Split on semicolons that end a statement (no stored procedures here, so a
// naive split is safe: no semicolons appear inside string literals in schema.sql).
const statements = sql
  .split('\n')
  .filter((line) => !line.trim().startsWith('--'))
  .join('\n')
  .split(';')
  .map((s) => s.trim())
  .filter(Boolean);

const body = `// GENERATED by scripts/build-schema.mjs — do not edit by hand.
export const SCHEMA_SQL: string[] = ${JSON.stringify(statements, null, 2)};
`;

writeFileSync(join(root, 'src/db/schema.generated.ts'), body);
console.log(`schema.generated.ts: ${statements.length} statements`);
